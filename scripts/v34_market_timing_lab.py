def find_anchor(input_root: Path, explicit: str | None = None) -> Path:
    if explicit:
        p = Path(explicit)
        if p.exists():
            if p.is_dir() and (p / "main.py").exists():
                return p / "main.py"
            return p
        raise FileNotFoundError(f"anchor not found: {p}")

    scored = []
    for p in input_root.rglob("*"):
        if not p.is_file():
            continue
        low = str(p).lower()
        if p.name != "main.py" and not p.name.endswith(".tar.gz"):
            continue
        score = 0
        if "v32" in low:
            score += 12
        if "runtime_verified" in low or "runtime-verified" in low:
            score += 8
        if "premium" in low:
            score += 4
        if "next_submit_v32" in low:
            score += 5
        if "submit_v32" in low:
            score += 5
        if score:
            scored.append((score, -len(p.parts), str(p), p))
    if not scored:
        raise FileNotFoundError(
            "No V32 anchor found under --input-root. Add the notebook/dataset "
            "containing SUBMIT_V32_RUNTIME_VERIFIED.tar.gz or pass --anchor."
        )
    return sorted(scored, reverse=True)[0][-1]


def prepare_anchor(anchor: Path, work: Path):
    root = work / "anchor"
    if root.exists():
        shutil.rmtree(root)
    root.mkdir(parents=True)

    if anchor.name.endswith(".tar.gz"):
        main = base.safe_extract(anchor, root)
        if main is None:
            raise RuntimeError(f"No main.py found in anchor archive {anchor}")
    elif anchor.name == "main.py":
        base.copy_tree(anchor.parent, root)
        main = root / "main.py"
    else:
        raise ValueError(f"unsupported anchor input: {anchor}")
    return root, main.relative_to(root)


def resolve_repo(input_root: Path, work: Path) -> Path:
    local = Path(__file__).resolve().parents[1]
    if (local / "src" / "kagv2" / "simulator.py").exists():
        return local
    for p in input_root.rglob("simulator.py"):
        if p.parent.name == "kagv2" and p.parent.parent.name == "src":
            root = p.parent.parent.parent
            if (root / "submission" / "base_controller.py").exists():
                return root
    return base.clone_repo(work)


