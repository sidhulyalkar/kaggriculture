def _reset():
    global PREV,DEFER,LAST_STEP
    PREV={}
    DEFER={k:0 for k in BASE_PRICE}
    LAST_STEP=-1

def _state(obs):
    private=obs.get("private",{}) or {}
    shed=private.get("shed",{}) or {}
    market=obs.get("market",{}) or {}
    inv=market.get("inventory",{}) or {}
    prices=market.get("prices",{}) or {}
