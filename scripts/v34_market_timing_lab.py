def _summary(df: pd.DataFrame, control="anchor") -> pd.DataFrame:
    keys=["opponent","seed","seat"]
    rows=[]
    ctl=df[df.candidate==control][keys+["score","margin","ok"]].rename(
        columns={"score":"control_score","margin":"control_margin","ok":"control_ok"}
    )
    for name,g in df.groupby("candidate"):
        merged=g.merge(ctl,on=keys,how="left")
        valid=merged[(merged.ok==True)&(merged.control_ok==True)].copy()  # noqa: E712
        delta=(valid.score-valid.control_score) if len(valid) else pd.Series(dtype=float)
        per_opp=valid.assign(delta=delta).groupby("opponent").delta.mean() if len(valid) else pd.Series(dtype=float)
        adaptive=valid[valid.opponent.isin(ADAPTIVE)]
        rows.append({
            "candidate":name,
            "games":int(len(g)),
            "invalid_games":int((g.ok!=True).sum()),  # noqa: E712
            "mean_score":float(pd.to_numeric(g.loc[g.ok==True,"score"],errors="coerce").mean()),  # noqa: E712
            "robust_delta":float(delta.mean()) if len(delta) else -1.0,
            "adaptive_delta":float((adaptive.score-adaptive.control_score).mean()) if len(adaptive) else 0.0,
            "worst_opponent_delta":float(per_opp.min()) if len(per_opp) else -1.0,
            "mean_margin_delta":float((valid.margin-valid.control_margin).mean()) if len(valid) else float("nan"),
        })
    out=pd.DataFrame(rows)
    out["utility"]=out.robust_delta+.75*out.adaptive_delta+.25*np.minimum(out.worst_opponent_delta,0)
    return out.sort_values(["utility","robust_delta"],ascending=False).reset_index(drop=True)


def _promotion(table: pd.DataFrame):
    candidates=table[(table.candidate!="anchor")&(table.invalid_games==0)].copy()
    passed=candidates[
        (candidates.robust_delta>=.015)&
        (candidates.adaptive_delta>=.04)&
        (candidates.worst_opponent_delta>=-.03)
    ]
    if passed.empty:
        return "anchor", "No V34 timing overlay cleared the robust promotion gate."
    r=passed.sort_values(["utility","robust_delta"],ascending=False).iloc[0]
    return str(r.candidate), (
        f"Promoted {r.candidate}: robust {r.robust_delta:+.4f}, "
        f"adaptive {r.adaptive_delta:+.4f}, worst opponent {r.worst_opponent_delta:+.4f}."
    )


def main():
    ap=argparse.ArgumentParser()
    ap.add_argument("--input-root",default="/kaggle/input")
    ap.add_argument("--work",default="/kaggle/working/v34_market_timing")
    ap.add_argument("--anchor",default=None,
                    help="Optional V32 tar.gz or main.py; auto-discovered when omitted")
    ap.add_argument("--workers",type=int,default=min(4,os.cpu_count() or 2))
    args=ap.parse_args()

    input_root=Path(args.input_root);work=Path(args.work);work.mkdir(parents=True,exist_ok=True)
    anchor=find_anchor(input_root,args.anchor)
    anchor_root,anchor_main=prepare_anchor(anchor,work)
    repo=resolve_repo(input_root,work)
    agents=base.discover(input_root,work)
    if not agents:
        raise RuntimeError("No public opponent agents discovered. Attach the V3.1 public-agent Kaggle inputs.")

    cfgs=configs()
    roots={n:make_candidate(work,anchor_root,anchor_main,n,c) for n,c in cfgs.items()}
    worker=work/"worker.py";worker.write_text(base.WORKER)

    targeted=[x for x in ("adaptive","score3094","soil","v16") if x in agents]
    if len(targeted)<2:targeted=list(agents)[:min(4,len(agents))]
    screen_seeds=[3401,3407,3413,3419]
    print("V34 SCREEN",len(cfgs),"candidates",targeted,"seeds",screen_seeds)
    jobs=base.jobs_for(roots,agents,list(cfgs),screen_seeds,targeted)
    screen=base.parallel(jobs,worker,repo,args.workers)
    screen.to_csv(work/"screen_games.csv",index=False)
    screen_table=_summary(screen)
    screen_table.to_csv(work/"screen_summary.csv",index=False)
    print(screen_table.to_string(index=False))

    finalists=screen_table[(screen_table.candidate!="anchor")&(screen_table.invalid_games==0)].head(3).candidate.tolist()
    held_names=["anchor",*finalists]
    held_seeds=[3511,3527,3541,3557,3571,3581]
    held_opponents=list(agents)
    print("V34 HELDOUT",held_names,"opponents",held_opponents,"seeds",held_seeds)
    jobs=base.jobs_for(roots,agents,held_names,held_seeds,held_opponents)
    held=base.parallel(jobs,worker,repo,args.workers)
    held.to_csv(work/"heldout_games.csv",index=False)
    held_table=_summary(held)
    held_table.to_csv(work/"heldout_summary.csv",index=False)
    print(held_table.to_string(index=False))

    selected,reason=_promotion(held_table)
    decision={
        "version":34,
        "selected_candidate":selected,
        "selection_reason":reason,
        "anchor":str(anchor),
        "anchor_main":str(anchor_main),
        "screen_opponents":targeted,
        "screen_seeds":screen_seeds,
        "heldout_opponents":held_opponents,
        "heldout_seeds":held_seeds,
        "finalists":finalists,
        "promotion_gate":{
            "min_robust_delta":.015,
            "min_adaptive_delta":.04,
            "min_worst_opponent_delta":-.03,
            "invalid_games":0,
        },
        "submission_ready":False,
        "production_note":"Winning overlay must be compiled into a single-file V32 runtime and pass the runtime submission contract before upload.",
    }
    (work/"decision.json").write_text(json.dumps(decision,indent=2,sort_keys=True))
    print(json.dumps(decision,indent=2))


if __name__=="__main__":
    main()
