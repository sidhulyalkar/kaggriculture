def make_candidate(work: Path, anchor_root: Path, anchor_main: Path, name: str, cfg: dict) -> Path:
    root=work/"candidates"/name
    if root.exists():shutil.rmtree(root)
    root.mkdir(parents=True)
    base.copy_tree(anchor_root,root/"anchor_parent")
    source=WRAPPER.replace("__CFG__",repr(cfg)).replace("__ANCHOR_MAIN__",repr(str(anchor_main)))
    (root/"main.py").write_text(source)
