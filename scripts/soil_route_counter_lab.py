def _premium_order(o):
    return isinstance(o,list) and len(o)>=3 and o[0]=="SELL" and o[1] in CFG["items"]

def _reorder(orders):
    mode=CFG.get("order_mode","keep")
    if mode=="premium_front":
        return sorted(orders,key=lambda o:0 if _premium_order(o) else 1)
    if mode=="premium_back":
        return sorted(orders,key=lambda o:1 if _premium_order(o) else 0)
    return orders

def agent(obs,config=None):
    global PREV,DEFER,LAST_STEP
    step=int(obs.get("step",0))
    if step==0 or step<=LAST_STEP:
        _reset()
    LAST_STEP=step

    action=copy.deepcopy(SOIL.agent(obs,config))
    market=list(action.get("market",[]) or [])
    shed,inv,prices=_state(obs)
    shed_total=sum(int(v or 0) for v in shed.values())

    delta={k:int(inv.get(k,10000))-int(PREV.get(k,inv.get(k,10000))) for k in CFG["items"]}
    PREV={k:int(inv.get(k,10000)) for k in CFG["items"]}

    out=[]
    terminal=step>=int(CFG["terminal_step"])
    pressure=shed_total>=int(CFG["shed_hard"])

    for o in market:
        if not _premium_order(o):
            out.append(o)
            continue
        item=o[1]
        try:q=max(0,int(o[2]))
        except Exception:
            out.append(o)
            continue

        shock=(delta.get(item,0)>=int(CFG["shock_threshold"])) if CFG["shock_threshold"]>0 else False
        price=float(prices.get(item,BASE_PRICE[item]))
        low=(price < BASE_PRICE[item]*float(CFG["price_ratio"])) if CFG["price_ratio"]>0 else False
        in_window=int(CFG["start_step"])<=step<int(CFG["terminal_step"])
        guard=in_window and not terminal and not pressure and (shock or low)

        if guard:
            DEFER[item]=int(DEFER.get(item,0))+q
            continue

        if DEFER.get(item,0):
            q += int(DEFER[item])
            DEFER[item]=0
        out.append(["SELL",item,q])

    if terminal and len(out)<10:
        present={o[1] for o in out if isinstance(o,list) and len(o)>=3 and o[0]=="SELL"}
        for item in CFG["items"]:
            if len(out)>=10:break
            if item in present:continue
            q=int(shed.get(item,0) or 0)
            if q>0 and DEFER.get(item,0):
                out.append(["SELL",item,q])
                DEFER[item]=0

